export function getAllBlogs() {
  return BLOG_POSTS;
}

export function getBlogBySlug(slug) {
  return BLOG_POSTS.find((post) => post.slug === slug);
}

/**
 * Returns a list of blogs combining featured posts and recent posts up to `limit`.
 * E.g., if there are 2 featured blogs and limit is 3, it returns the 2 featured + 1 most recent.
 */
export function getFeaturedOrRecentBlogs(limit = 3) {
  const featured = BLOG_POSTS.filter((post) => post.featured);
  if (featured.length >= limit) {
    return featured.slice(0, limit);
  }
  const nonFeatured = BLOG_POSTS.filter((post) => !post.featured);
  return [...featured, ...nonFeatured].slice(0, limit);
}

export function getRelatedBlogs(currentSlug, category, limit = 3) {
  const related = BLOG_POSTS.filter(
    (post) => post.slug !== currentSlug && post.category === category,
  );
  if (related.length > 0) return related.slice(0, limit);
  return BLOG_POSTS.filter((post) => post.slug !== currentSlug).slice(0, limit);
}

export function getCategories() {
  return ["All", "Latest Posts", "Announcements", "Tips & Articles"];
}

export function getAllTags() {
  const tagSet = new Set();
  BLOG_POSTS.forEach((post) => {
    post.tags.forEach((tag) => tagSet.add(tag));
  });
  return Array.from(tagSet);
}
